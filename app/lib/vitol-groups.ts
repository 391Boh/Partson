export function vitolGroupFor(input: { categoryPath: string[]; categoryId?: string; name?: string }): VitolGroup {
  const path = input.categoryPath.map(norm);
  for (let level = path.length - 1; level >= 0; level -= 1) {
    const name = path[level];
    const child = path[level + 1] || "";
    if (name.startsWith("інструмент alloid building tools") && BUILDING_CONSUMABLES.some((key) => child.includes(key))) {
      return "Свердла, диски та абразив";
    }
    if (name.startsWith("інструмент alloid") && child.includes("пневмоінструмент")) return "Інструмент для ремонту авто";
    const hit = CATEGORY_RULES.find(([key]) => name.startsWith(key));
    if (hit) return hit[1];
  }
  if (input.categoryId && CATEGORY_ID[input.categoryId]) return CATEGORY_ID[input.categoryId];
  const name = input.name || "";
  const byName = NAME_KEYWORDS.find(([pattern]) => pattern.test(name));
  return byName ? byName[1] : VITOL_FALLBACK_GROUP;
}
