const normalize = (label: string) => label.trim().replace(/\s+/g, " ").toLocaleLowerCase("uk-UA");
const guidesByLabel = new Map<string, CatalogSelectionGuide>(
  Object.entries(GUIDES).map(([label, guide]) => [normalize(label), guide])
);

export const getCatalogSelectionGuide = (...labels: Array<string | undefined>) => {
  for (const label of labels) {
    const guide = label ? guidesByLabel.get(normalize(label)) : undefined;
    if (guide) return guide;
  }
  return undefined;
};

