// Snapshot the showcase's real product photos as small, content-hashed WebP.
// Run with a local server: npm run generate:home-arrival-images
// Override HOME_ARRIVAL_IMAGE_ORIGIN to select a different catalog server.
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { HOME_ARRIVAL_CARDS, HOME_ARRIVAL_FLOATING } from "../app/lib/home-arrivals";
import { PRODUCT_IMAGE_FALLBACK_PATH } from "../app/lib/product-image-constants";
import { buildProductImagePath } from "../app/lib/product-image-path";

async function main() {
  const origin = process.env.HOME_ARRIVAL_IMAGE_ORIGIN || "http://localhost:3000";
  const outputDir = path.join(process.cwd(), "public/images/home/arrivals");
  const manifest: Record<string, { src: string; width: number; height: number }> = {};
  const fallback = await readFile(path.join(process.cwd(), "public", PRODUCT_IMAGE_FALLBACK_PATH));
  const hash = (buffer: Buffer) => createHash("sha256").update(buffer).digest("hex");
  let originalBytes = 0;
  let thumbnailBytes = 0;
  await mkdir(outputDir, { recursive: true });

  // Complete every download before updating the manifest. An unavailable image
  // must fail the generation, never replace a known product with a placeholder.
  for (const [items, size] of [[HOME_ARRIVAL_CARDS, 224], [HOME_ARRIVAL_FLOATING, 360]] as const) {
    for (const { code } of items) {
      const response = await fetch(new URL(buildProductImagePath(code, undefined, { noFallback: true }), origin), {
        redirect: "error", signal: AbortSignal.timeout(15_000),
      });
      if (!response.ok || !response.headers.get("content-type")?.startsWith("image/")) {
        throw new Error(`Photo unavailable for ${code}: ${response.status}`);
      }
      const input = Buffer.from(await response.arrayBuffer());
      if (hash(input) === hash(fallback)) throw new Error(`Placeholder returned for ${code}`);
      const { data, info } = await sharp(input).rotate().resize({
        width: size, height: size, fit: "inside", withoutEnlargement: true,
      }).webp({ quality: 78, effort: 6 }).toBuffer({ resolveWithObject: true });
      const filename = `${code.replace(/[^a-z0-9-]/gi, "").replace(/^-+/, "")}-${hash(data).slice(0, 12)}.webp`;
      await writeFile(path.join(outputDir, filename), data);
      manifest[code] = { src: `/images/home/arrivals/${filename}`, width: info.width, height: info.height };
      originalBytes += input.length;
      thumbnailBytes += data.length;
    }
  }

  await writeFile(path.join(process.cwd(), "app/generated/home-arrival-images.ts"),
    `// Generated by scripts/generate-home-arrival-images.ts.\n// Provenance: real 1C product photos, keyed by their exact product codes.\n// Regenerate explicitly when showcase products/photos change; no runtime 1C dependency.\nexport const HOME_ARRIVAL_IMAGES: Record<string, { src: string; width: number; height: number }> = ${JSON.stringify(manifest, null, 2)};\n`);
  console.log(`Homepage arrivals: ${Object.keys(manifest).length} photos, ${originalBytes} → ${thumbnailBytes} bytes`);
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
