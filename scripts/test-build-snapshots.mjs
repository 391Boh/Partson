import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { build } from 'esbuild';
import { prepareSnapshotBuild } from './build-site.mjs';
const root = mkdtempSync(path.join(tmpdir(), 'partson-build-inputs-'));
assert.throws(() => prepareSnapshotBuild({ root }), /sync:catalog/);
const compiled = prepareSnapshotBuild({ root, compileOnly: true });
assert.equal(compiled.env.ONEC_BUILD_SNAPSHOT_ONLY, '1');
assert(readFileSync(path.join(root, 'app/generated/group-preview-manifest.ts'), 'utf8').includes('export default'));
const directory = path.join(root, '.cache/build-inputs');
writeFileSync(path.join(directory, 'manifest.json'), JSON.stringify({ version: 1, snapshots: 2, endpoints: ['getprod', 'getauto'] }));
assert.equal(prepareSnapshotBuild({ root }).env.ONEC_BUILD_SNAPSHOT_ONLY, '1');
process.env.ONEC_BUILD_SNAPSHOT_DIR = directory;
process.env.ONEC_RECORD_BUILD_SNAPSHOTS = '1';
const snapshotBundle = await build({ entryPoints: ['app/api/_lib/oneC-build-snapshots.js'], bundle: true, write: false, platform: 'node', format: 'esm' });
const snapshots = await import('data:text/javascript;base64,' + Buffer.from(snapshotBundle.outputFiles[0].text).toString('base64'));
const saved = { status: 200, contentType: 'application/json', text: '{"items":[1]}' };
snapshots.recordBuildSnapshot('getprod', 'POST:getprod:{}', saved);
assert.deepEqual(snapshots.readBuildSnapshot('getprod', 'POST:getprod:{}'), saved);
assert.equal(snapshots.readBuildSnapshot('getprod', 'different'), null);
snapshots.recordBuildSnapshot('create', 'POST:create:{}', saved);
assert.equal(snapshots.readBuildSnapshot('create', 'POST:create:{}'), null, 'Mutating endpoints never become build inputs');
process.env.ONEC_BUILD_SNAPSHOT_ONLY = '1';
delete process.env.ONEC_AUTH_HEADER;
const client = await build({ entryPoints: ['app/api/_lib/oneC.js'], bundle: true, write: false, platform: 'node', format: 'esm' });
const { oneCRequest } = await import('data:text/javascript;base64,' + Buffer.from(client.outputFiles[0].text).toString('base64'));
assert.equal((await oneCRequest('getprod', { method: 'POST', body: {} })).text, saved.text, 'Build reads prepared input without credentials or a live connection');
assert.equal((await oneCRequest('getauto', { method: 'POST', body: {} })).status, 503, 'Missing input fails fast instead of calling 1C');
assert.equal((await oneCRequest('getprod', { method: 'POST', body: { Реалізація: 1 } })).status, 503, 'Build can never mutate stock');
mkdirSync(path.join(root, 'check'), { recursive: true });
console.log('PASS explicit snapshot preparation, private recording, cache keys, offline reads, missing inputs and stock-write prevention');
