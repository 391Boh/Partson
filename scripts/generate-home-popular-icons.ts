// Pre-renders the homepage "popular sections" icons (HomeSeoLinks) as 72px
// WebP thumbnails. They are shown at 36px, but the originals — category PNGs,
// car-brand SVGs, producer logos — added up to ~400 KB. Run after changing
// the lists in app/lib/home-popular-links.ts:
//   npm run generate:home-popular-icons
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

import { getHomePopularIconSources } from "../app/lib/home-popular-links";

const projectRoot = process.cwd();
const publicDir = path.join(projectRoot, "public");
const outputDir = path.join(publicDir, "images", "home", "popular-icons");
const manifestPath = path.join(projectRoot, "app", "generated", "home-popular-icons.ts");
const SIZE = 72;

const toFileName = (src: string) =>
  decodeURIComponent(src)
    .replace(/^\/+/, "")
    .replace(/\.[a-z0-9]+$/i, "")
    .replace(/[^a-zA-Z0-9_-]+/g, "-")
    .toLowerCase() + ".webp";

const main = async () => {
  await mkdir(outputDir, { recursive: true });
  const manifest: Record<string, string> = {};
  let originalBytes = 0;
  let thumbBytes = 0;
  for (const src of Array.from(new Set(getHomePopularIconSources()))) {
    const sourcePath = path.join(publicDir, decodeURIComponent(src));
    const input = await readFile(sourcePath).catch(() => null);
    if (!input) {
      console.warn(`[home-popular-icons] missing ${src}, keeping the original`);
      continue;
    }
    const fileName = toFileName(src);
    const output = await sharp(input, { density: src.endsWith(".svg") ? 300 : 72 })
      .resize(SIZE, SIZE, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .webp({ quality: 82, alphaQuality: 90, effort: 6 })
      .toBuffer();
    await writeFile(path.join(outputDir, fileName), output);
    manifest[src] = `/images/home/popular-icons/${fileName}`;
    originalBytes += input.length;
    thumbBytes += output.length;
  }
  const body = `// Generated by scripts/generate-home-popular-icons.ts — do not edit.
// Original icon path → 72px WebP thumbnail.
export const HOME_POPULAR_ICONS: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;
  await writeFile(manifestPath, body);
  console.log(
    `[home-popular-icons] ${Object.keys(manifest).length} icons: ${Math.round(originalBytes / 1024)} KB → ${Math.round(thumbBytes / 1024)} KB`
  );
};

void main();
