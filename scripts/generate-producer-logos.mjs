// Lists /public/Brands for the catalog product card, which cannot read the
// directory at runtime (client component). Keys use the same normalization as
// app/lib/producer-logo-match.ts. Runs in `npm run build`; rerun after adding
// a logo file: node scripts/generate-producer-logos.mjs
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const key = (value) => value.toLowerCase().normalize("NFKD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "");
const files = readdirSync(path.join(root, "public", "Brands"))
  .filter((name) => /\.(png|jpe?g|webp|svg)$/i.test(name))
  .sort();
const entries = {};
for (const name of files) {
  const k = key(name.replace(/\.[^.]+$/, ""));
  if (k && !entries[k]) entries[k] = `/Brands/${encodeURIComponent(name)}`;
}
writeFileSync(
  path.join(root, "app", "generated", "producer-logos.ts"),
  `// Generated by scripts/generate-producer-logos.mjs — do not edit.\n// Normalized producer key → logo in /public/Brands.\nexport const PRODUCER_LOGO_FILES: Record<string, string> = ${JSON.stringify(entries, null, 2)};\n`
);
console.log(`[producer-logos] ${Object.keys(entries).length} logos`);
